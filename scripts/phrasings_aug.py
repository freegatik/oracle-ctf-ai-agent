def merge_into(profile_params):
    """Добавить EXTRA_PHRASES к базовым phrases каждого параметра (in place)."""
    for nm, extra in EXTRA_PHRASES.items():
        if nm in profile_params:
            profile_params[nm]["phrases"] = list(profile_params[nm]["phrases"]) + extra
